class TestResult:
    def __init__(self, name: str):
        self.name = name
        self.passed = True
        self.steps = []

    def check(self, step_name: str, condition: bool, details: str = ""):
        if not condition:
            self.passed = False
        self.steps.append((step_name, condition, details))

def run_dialogue(dialogue_name: str, vacancy_title: str, turns: list) -> TestResult:
    res = TestResult(dialogue_name)
    cand_history = []
    our_history = []

    for turn_idx, (cand_input, expected_checks) in enumerate(turns, 1):
        cand_hist_str = " \n ".join(cand_history)
        our_hist_str = " \n ".join(our_history)

        reply, is_disq, disq_reason = generate_human_reply(
            cand_text=cand_input,
            ad_title=vacancy_title,
            cand_history_only=cand_hist_str,
            our_history=our_hist_str
        )

        cand_history.append(cand_input)
        our_history.append(reply)

        # Проверка проверок (assertions)
        for check_name, check_fn in expected_checks.items():
            passed = check_fn(reply, is_disq, disq_reason)
            res.check(f"Ход {turn_idx}: {check_name}", passed, f"Реплика бота: '{reply[:80]}...' | disq={is_disq}")

    return res

