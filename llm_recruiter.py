def get_api_key() -> str:
    api_key = os.environ.get("GEMINI_API_KEY", "").strip()
    if not api_key:
        env_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), ".env")
        if os.path.exists(env_path):
            with open(env_path, "r", encoding="utf-8") as f:
                for line in f:
                    if line.startswith("GEMINI_API_KEY="):
                        api_key = line.split("=", 1)[1].strip()
                        break
    return api_key

def generate_llm_reply(
    cand_text: str,
    ad_title: str,
    facility_info: dict,
    cand_history: str = "",
    our_history: str = "",
    cand_name: str = ""
) -> Optional[str]:
    """
    Генерирует ответ через Gemini LLM с полным контекстом диалога и регламентом возражений.
    Возвращает строку с ответом, либо None в случае отсутствия ключа / ошибки.
    """
    api_key = get_api_key()
    if not api_key:
        return None

    facility_context = (
        f"ВАКАНСИЯ И ОБЪЕКТ:\n"
        f"Название объявления: {ad_title}\n"
        f"Объект: {facility_info.get('title', '')}\n"
        f"Обязанности: {facility_info.get('duties', '')}\n"
        f"Оплата: {facility_info.get('pay', '')}\n"
        f"Проживание: {facility_info.get('housing', '')}\n"
        f"Питание: {facility_info.get('food', '')}\n"
        f"Дорога/проезд: {facility_info.get('transport', '')}\n"
        f"График: {facility_info.get('schedule', '')}\n"
        f"Медкнижка: {facility_info.get('medbook', '')}\n"
    )

    history_context = ""
    if our_history or cand_history:
        history_context = (
            f"ПРЕДЫДУЩАЯ ИСТОРИЯ ДИАЛОГА:\n"
            f"Сообщения кандидата ранее:\n{cand_history}\n\n"
            f"Наши предыдущие ответы:\n{our_history}\n"
        )

    user_prompt = (
        f"{facility_context}\n"
        f"{history_context}\n"
        f"ИМЯ СОБЕСЕДНИКА: {cand_name or 'Не указано'}\n"
        f"НОВОЕ СООБЩЕНИЕ ОТ КАНДИДАТА: \"{cand_text}\"\n\n"
        f"Сформулируй естественный, краткий (1-3 коротких предложения) ответ от лица рекрутера с применением утвержденного регламента отработки возражений."
    )

    learned_rules_text = get_learned_rules_for_prompt()
    full_system_prompt = f"{SYSTEM_PROMPT}\n{learned_rules_text}"

    models_to_try = ["gemini-3.1-flash-lite", "gemini-3.1-flash-lite-preview", "gemini-2.5-flash", "gemini-3.5-flash-lite"]
    for m in models_to_try:
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{m}:generateContent?key={api_key}"
        gen_cfg = {
            "temperature": 0.65,
            "maxOutputTokens": 300
        }
        if "gemini-3" in m:
            gen_cfg["thinkingConfig"] = {"thinkingBudget": 0}

        payload = {
            "system_instruction": {
                "parts": [{"text": full_system_prompt}]
            },
            "contents": [
                {
                    "role": "user",
                    "parts": [{"text": user_prompt}]
                }
            ],
            "generationConfig": gen_cfg
        }
        try:
            resp = requests.post(url, json=payload, timeout=8)
            if resp.status_code == 200:
                data = resp.json()
                candidates = data.get("candidates", [])
                if candidates:
                    parts = candidates[0].get("content", {}).get("parts", [])
                    if parts and "text" in parts[0]:
                        reply = parts[0]["text"].strip()
                        # Safety filter: passport photo request on Avito is forbidden
                        if "фото паспорта" in reply.lower() and ("пришлите" in reply.lower() or "скиньте" in reply.lower()):
                            reply = reply.replace("фото паспорта", "подтверждение гражданства РФ")
                        # Keep it strictly under 450 chars for Avito
                        if len(reply) > 450:
                            dot_idx = reply[:450].rfind(".")
                            if dot_idx > 100:
                                reply = reply[:dot_idx + 1]
                            else:
                                reply = reply[:450]
                        return reply
            else:
                logger.warning(f"Model {m} returned {resp.status_code}: {resp.text[:100]}")
        except Exception as e:
            logger.warning(f"Model {m} request failed: {e}")
            continue

    return None
