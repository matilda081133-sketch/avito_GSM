def strip_name_greetings(text: str) -> str:
    """Удаляет любые обращения по имени в начале сообщения (например: 'Максим, добрый день' -> 'Добрый день')."""
    if not text:
        return text
    text = re.sub(r'^[А-ЯЁA-Za-z][а-яёA-Za-z0-9_-]+,\s*(здравствуйте|добрый день|добрый вечер|приветствую)', r'\1', text, flags=re.IGNORECASE)
    text = re.sub(r'^(здравствуйте|добрый день|добрый вечер|приветствую)[,\s]+[А-ЯЁA-Za-z][а-яёA-Za-z0-9_-]+[!\.,\s]*', r'\1! ', text, flags=re.IGNORECASE)
    text = re.sub(r'^[А-ЯЁA-Za-z][а-яёA-Za-z0-9_-]+,\s*', '', text)
    text = text.strip()
    if text:
        text = text[0].upper() + text[1:]
    return text

def generate_llm_reply(
    cand_text: str,
    ad_title: str,
    facility_info: dict,
    cand_history: str = "",
    our_history: str = "",
    cand_name: str = "",
    dialogue_transcript: str = "",
    profile: dict = None,
    max_bot_link: str = "",
    is_ready_to_sign_up: bool = False,
    is_fully_qualified: bool = False,
    is_non_russian: bool = False,
    has_rf_confirmed: bool = False,
    ad_description: str = ""
) -> Optional[str]:
    cand_text_lower = (cand_text or "").lower()
    if re.search(r'цыган|циган|ромал', cand_text_lower):
        logger.warning(f"Категорический отказ кандидату (цыгане/ромала): {cand_text}")
        return "Здравствуйте! К сожалению, по требованиям службы безопасности предприятия и регламенту производства согласование на данный объект невозможно, набор закрыт. Спасибо за обращение!"

    keys_pool = get_api_keys()
    if not keys_pool:
        return None

    # Очистка текста объявления от лишних HTML-тегов для чистого восприятия нейросетью
    clean_desc = re.sub(r'<[^>]+>', ' ', ad_description or '').strip()
    clean_desc = re.sub(r'\s+', ' ', clean_desc)
    if len(clean_desc) > 1500:
        clean_desc = clean_desc[:1500] + "..."

    fac_title = facility_info.get('title', 'Объект компании')
    fac_name = facility_info.get('facility_name', '')
    fac_duties = facility_info.get('duties', '')
    fac_pay = facility_info.get('pay', '')
    fac_food = facility_info.get('food', '')
    fac_housing = facility_info.get('housing', '')
    fac_shift = facility_info.get('shift_text', '')

    facility_context = (
        f"КАРТОЧКА ОБЪЯВЛЕНИЯ, НА КОТОРОЕ НАПИСАЛ КАНДИДАТ:\n"
        f"• Название вакансии: {ad_title}\n"
        f"• Объект: {fac_title} ({fac_name})\n"
        f"• Обязанности: {fac_duties}\n"
        f"• Оплата: {fac_pay}\n"
        f"• Питание: {fac_food}\n"
        f"• Проживание: {fac_housing}\n"
        f"• ТЕКСТОВОЕ НАПОЛНЕНИЕ ОБЪЯВЛЕНИЯ НА АВИТО:\n{clean_desc}\n\n"
        f"⚠️ СТРОГОЕ ТРЕБОВАНИЕ: Внимательно опирайся на текстовое наполнение этого конкретного объявления! "
        f"Если соискатель спрашивает про ставку, график, обязанности или проживание — отвечай строго в соответствии "
        f"с текстом объявления и условиями данного объекта."
    )

    if dialogue_transcript:
        dialogue_block = f"ПОЛНАЯ ИСТОРИЯ ПЕРЕПИСКИ В ЧАТЕ:\n{dialogue_transcript}"
    else:
        history_parts = []
        if our_history:
            history_parts.append(f"Наши ответы ранее:\n{our_history}")
        if cand_history:
            history_parts.append(f"Сообщения кандидата ранее:\n{cand_history}")
        dialogue_block = "\n\n".join(history_parts)

    profile_block = ""
    if profile:
        subj = profile.get("target_subject", "кандидат").upper()
        
        # 1. Возраст
        age_val = profile.get("age")
        if age_val:
            if age_val > 55:
                age_instruction = f"{age_val} лет (ВНИМАНИЕ: ВОЗРАСТ {age_val} ЛЕТ ПРЕВЫШАЕТ 55 ЛЕТ! КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО ПЕРЕСПРАШИВАТЬ ВОЗРАСТ! ПО РЕГЛАМЕНТУ СБ СТРОГО ВЕЖЛИВЫЙ ОТКАЗ: на данном объекте согласование строго до 55 лет!)"
            elif age_val < 20:
                age_instruction = f"{age_val} лет (ВНИМАНИЕ: ВОЗРАСТ {age_val} ЛЕТ МЕНЬШЕ 20 ЛЕТ! ПО РЕГЛАМЕНТУ СБ СТРОГО ВЕЖЛИВЫЙ ОТКАЗ: согласование строго с 20 лет!)"
            else:
                age_instruction = f"{age_val} лет (УЖЕ ИЗВЕСТЕН! КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО ПЕРЕСПРАШИВАТЬ ВОЗРАСТ!)"
        else:
            age_instruction = "не указан (уточни возраст, если он не указан в истории)"

        # 2. Гражданство
        cit_val = profile.get("has_rf_passport")
        if cit_val is True:
            cit_instruction = "подтверждено (паспорт РФ на руках, УЖЕ ИЗВЕСТНО! КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО СПРАШИВАТЬ ПРО ГРАЖДАНСТВО ИЛИ ПАСПОРТ!)"
        elif cit_val is False:
            cit_instruction = "НЕТ ПАСПОРТА РФ (УЖЕ ИЗВЕСТНО И ПОДТВЕРЖДЕНО! КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО СПРАШИВАТЬ ЕСТЬ ЛИ ПАСПОРТ! СТРОГО ВЕЖЛИВЫЙ ОТКАЗ ПО РЕГЛАМЕНТУ СБ!)"
        else:
            cit_instruction = "не указано (уточни паспорт РФ, если не гражданин РФ)"

        # 3. Город проживания / выезда
        city_val = profile.get("origin_city")
        if city_val:
            city_instruction = f"{city_val} (УЖЕ ИЗВЕСТЕН! КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО СПРАШИВАТЬ, ИЗ КАКОГО ГОРОДА ПЛАНИРУЕТ ВЫЕЗЖАТЬ!)"
        else:
            city_instruction = "не указан (уточни город выезда/проживания)"

        # 4. Дата выезда / готовность
        date_val = profile.get("departure_date")
        if date_val:
            date_instruction = f"{date_val} (УЖЕ ИЗВЕСТНА! КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО ПЕРЕСПРАШИВАТЬ ДАТУ ВЫЕЗДА!)"
        else:
            date_instruction = "не указана"

        # 5. Номер телефона
        phone_val = profile.get("phone_number")
        if phone_val:
            phone_instruction = f"{phone_val} (УЖЕ ПОЛУЧЕН! КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО ПОВТОРНО СПРАШИВАТЬ ТЕЛЕФОН!)"
        else:
            phone_instruction = "не указан (запросить для бронирования места)"

        # 6. Пол
        gender_val = profile.get("gender")
        gender_instruction = f"{gender_val} (УЖЕ ИЗВЕСТЕН! НЕ ПЕРЕСПРАШИВАТЬ!)" if gender_val else "не указан"

        profile_block = (
            f"СТРУКТУРИРОВАННАЯ КАРТОЧКА КАНДИДАТА (НЕСГОРАЕМАЯ ПАМЯТЬ КВАЛИФИКАЦИИ):\n"
            f"• ДЛЯ КОГО ИЩЕТ РАБОТУ: {subj} (СТРОГО! Никогда не путай и не называй другим лицом!)\n"
            f"• ПОЛ: {gender_instruction}\n"
            f"• ВОЗРАСТ: {age_instruction}\n"
            f"• ГРАЖДАНСТВО РФ: {cit_instruction}\n"
            f"• ГОРОД ВЫЕЗДА / ПРОЖИВАНИЯ: {city_instruction}\n"
            f"• ДАТА ГОТОВНОСТИ К ВЫЕЗДУ: {date_instruction}\n"
            f"• КОНТАКТНЫЙ ТЕЛЕФОН: {phone_instruction}\n\n"
            f"⚠️ ЖЕЛЕЗНОЕ ПРАВИЛО КВАЛИФИКАЦИИ: Любой параметр, помеченный как УЖЕ ИЗВЕСТЕН / ПОДТВЕРЖДЕН / ПОЛУЧЕН, "
            f"КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО задавать или переспрашивать повторно! Не раздражай соискателя повторами!\n\n"
        )

    non_rus_block = ""
    # Включаем предупреждение по нерусским именам ТОЛЬКО если паспорт РФ еще не проверялся (не True и не False)
    if is_non_russian and not has_rf_confirmed and (profile and profile.get("has_rf_passport") is None):
        non_rus_block = (
            f"\n\n⚠️ ВНИМАНИЕ: У КАНДИДАТА ИЛИ ЕГО РОДСТВЕННИКА НЕ РУССКОЕ ИМЯ!\n"
            f"Нерусские имена ДОЛЖНЫ НАСТОРАЖИВАТЬ. Гражданство РФ еще НЕ подтверждено соискателем.\n"
            f"ПРАВИЛО: В первую очередь вежливо уточни наличие паспорта гражданина РФ.\n"
        )

    # В первичном диалоге на Авито ссылку в МАКС не выдаем — ссылка идет только после звонка рекрутера!
    max_block = "" 

    user_prompt = (
        f"{facility_context}\n\n"
        f"{profile_block}"
        f"{dialogue_block}\n\n"
        f"ОБРАЩЕНИЕ: строго на «вы», КАТЕГОРИЧЕСКИ БЕЗ ИМЕНИ (не использовать имя соискателя в ответе)!\n"
        f"САМОЕ СВЕЖЕЕ СООБЩЕНИЕ ОТ КАНДИДАТА: \"{cand_text}\"\n"
        f"{max_block}\n"
        f"Напиши естественный, умный, чуткий ответ соискателю от лица рекрутера прямого работодателя. "
        f"КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО обращаться к кандидату по имени (имена в профилях часто некорректные). "
        f"Если кандидат внес уточнение или поправил нас — мгновенно и вежливо подстройся. "
        f"Ответ держи в пределах 1-3 предложений (до 400-500 символов)."
    )

    learned_rules_text = get_learned_rules_for_prompt()
    full_system_prompt = f"{SYSTEM_PROMPT}\n\nДОПОЛНИТЕЛЬНЫЕ ПРАВИЛА ИЗ БАЗЫ ЗНАНИЙ:\n{learned_rules_text}"


    # -------------------------------------------------------------------------
    # 0. ПРИОРИТЕТ 1: БОЕВОЙ ПЛАТНЫЙ ШЛЮЗ PROXYAPI (OpenAI GPT-4o-mini)
    # Мгновенный ответ (< 1.2 сек), максимальное качество диалога без лимитов Google.
    # -------------------------------------------------------------------------
    proxy_key = get_proxyapi_key()
    if proxy_key:
        try:
            proxy_url = "https://api.proxyapi.ru/openai/v1/chat/completions"
            payload = {
                "model": "gpt-4o-mini",
                "messages": [
                    {"role": "system", "content": full_system_prompt},
                    {"role": "user", "content": user_prompt}
                ],
                "max_tokens": 450,
                "temperature": 0.7
            }
            headers = {
                "Authorization": f"Bearer {proxy_key}",
                "Content-Type": "application/json"
            }
            resp = requests.post(proxy_url, json=payload, headers=headers, timeout=12)
            if resp.status_code == 200:
                data = resp.json()
                choices = data.get("choices", [])
                if choices:
                    reply = choices[0].get("message", {}).get("content", "").strip()
                    if reply:
                        if len(reply) > 550:
                            dot_idx = reply[:550].rfind(".")
                            if dot_idx > 100:
                                reply = reply[:dot_idx + 1]
                            else:
                                reply = reply[:550]
                        return strip_name_greetings(reply)
            else:
                logger.warning(f"ProxyAPI HTTP {resp.status_code}: {resp.text[:100]}. Переход на резерв Gemini...")
        except Exception as e:
            logger.warning(f"ProxyAPI request error: {e}. Переход на резерв Gemini...")

    # -------------------------------------------------------------------------
    # 1. РЕЗЕРВНЫЙ ПУЛ: GOOGLE GEMINI (8 КЛЮЧЕЙ С АВТОРОТАЦИЕЙ)
    # -------------------------------------------------------------------------
    models_to_try = [
        "gemini-flash-lite-latest",
        "gemini-flash-latest",
        "gemini-3.8-flash",
        "gemini-3.5-flash-lite"
    ]

    for api_key in keys_pool:
        key_exhausted = False
        for m in models_to_try:
            if key_exhausted:
                break
            url = f"https://generativelanguage.googleapis.com/v1beta/models/{m}:generateContent?key={api_key}"
            # We try zero thinking budget first so response comes back in < 1s without burning output tokens on internal CoT
            configs_to_try = [
                {"temperature": 0.7, "maxOutputTokens": 600, "thinkingConfig": {"thinkingBudget": 0}},
                {"temperature": 0.7, "maxOutputTokens": 600}
            ]
            
            for gen_cfg in configs_to_try:
                payload = {
                    "system_instruction": {
                        "parts": [{"text": full_system_prompt}]
                    },
                    "contents": [
                        {
                            "role": "user",
                            "parts": [{"text": user_prompt}]
                        }
                    ],
                    "generationConfig": gen_cfg
                }
                try:
                    _wait_for_rate_limit()
                    resp = requests.post(url, json=payload, timeout=18)
                    if resp.status_code == 200:
                        data = resp.json()
                        candidates = data.get("candidates", [])
                        if candidates:
                            parts = candidates[0].get("content", {}).get("parts", [])
                            if parts and "text" in parts[0]:
                                reply = parts[0]["text"].strip()
                                if len(reply) > 550:
                                    dot_idx = reply[:550].rfind(".")
                                    if dot_idx > 100:
                                        reply = reply[:dot_idx + 1]
                                    else:
                                        reply = reply[:550]
                                return strip_name_greetings(reply)
                    elif resp.status_code == 400 and "thinkingConfig" in gen_cfg:
                        # Model might not support thinkingConfig, retry without it
                        continue
                    elif resp.status_code == 429:
                        logger.warning(f"Key {api_key[:8]}... hit 429. Rotating to next key in pool...")
                        key_exhausted = True
                        break  # Break config loop
                    else:
                        logger.warning(f"Model {m} returned {resp.status_code}: {resp.text[:100]}")
                        break
                except Exception as e:
                    logger.warning(f"Model {m} request failed: {e}")
                    break
    return None
