def extract_gender(text: str, name: str = "") -> str:
    combined = ((text or "") + " " + (name or "")).lower()
    if any(k in combined for k in ["парой", "паре", "с мужем", "с парнем", "с женой", "вдвоем", "семейн", "для пар", "парам"]):
        return "Пара"
    if any(k in combined for k in ["женщин", "девушк", "женск", "я одна", "сама"]):
        return "Жен"
    if any(k in combined for k in ["мужчин", "парен", "мужск", "я один", "сам"]):
        return "Муж"
    for word in re.findall(r'[а-яё]+', combined):
        if word in COMMON_MALE_NAMES:
            return "Муж"
        if word in COMMON_FEMALE_NAMES:
            return "Жен"
    return ""

