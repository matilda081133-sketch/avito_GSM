    cutoff_ts = CHAT_SESSION_CUTOFFS.get(chat_id, 0)
    if cutoff_ts > 0:
        msgs = [m for m in msgs if m.get('created', 0) >= cutoff_ts]
        if not msgs:
            return False

    # Игнорируем технические сервисные заголовки интеграций (Wappi и т.д.)
    def is_tech_msg(m):
        txt = m.get('content', {}).get('text', '').lower()
        return 'wappi:' in txt or 'wappi :' in txt or ('объявление:' in txt and 'ссылка на объявление:' in txt)

    msgs_clean = [m for m in msgs if not is_tech_msg(m)]
    if not msgs_clean:
        return False
    last_msg = msgs_clean[-1]

    # Если последнее сообщение отправлено сотрудником/менеджером (Натальей) — ожидаем ответ соискателя
    if last_msg.get('author_id') in STAFF_USER_IDS:
        return False
    deal = find_b24_deal_for_chat(chat_id)
    deal_id = str(deal.get("ID", "")) if deal else ""
    deal_stage = str(deal.get("STAGE_ID", "")) if deal else ""
    deal_comments = str(deal.get("COMMENTS", "")) if deal else ""

    # Получаем код вакансии (autoload_item_id) и полное описание объявления из API Авито + из сделки Битрикс24
    item_details = active_client.get_item_details(item_id) if item_id else {}
    vacancy_code = item_details.get("autoload_item_id", "")
    if not vacancy_code and deal_comments:
        m_code = re.search(r'\[B\]Код вакансии:\[/B\]\s*([^\n\r\[]+)', deal_comments)
        if m_code:
            vacancy_code = m_code.group(1).strip()
    ad_description = f"{item_details.get('description', '')} {deal_comments}"

    # Если последнее сообщение отправлено нами (ассистентом) — ожидаем ответ соискателя
    if last_msg.get('author_id') == active_user_id:
        return False

    valeria_text = last_msg.get('content', {}).get('text', '').strip()
    if not valeria_text:
        return False

    cand_disp = (cand_name or 'КАНДИДАТ').upper()
    print(f"\n[{datetime.datetime.now().strftime('%H:%M:%S')}]{cab_label} 🔥 СООБЩЕНИЕ ОТ {cand_disp} [{item_title}]: '{valeria_text}'")

