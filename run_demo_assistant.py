def detect_facility(text: str) -> str:
    t = (text or "").lower()
    if any(k in t for k in ["тепофол", "кашир", "утеплит", "изоляци"]):
        return "TEPOFOL"
    elif any(k in t for k in ["смарт", "балаших", "салтыков", "кучин", "зоо"]):
        return "SMART_LOCAL"
    return "ABI"

def extract_phone_number(text: str) -> str:
    if not text:
        return ""
    raw = re.sub(r'[^\d+]', '', text)
    m = re.search(r'(?:\+?7|8)(9\d{9})', raw)
    if m:
        return f"+7{m.group(1)}"
    m2 = re.search(r'(?:\+?7|8)[\s\-\(]*(\d{3})[\s\-\)]*(\d{3})[\s\-]*(\d{2})[\s\-]*(\d{2})', text)
    if m2:
        return f"+7{m2.group(1)}{m2.group(2)}{m2.group(3)}{m2.group(4)}"
    return ""

def extract_age(text: str) -> int:
    if not text:
        return 0
    t = text.lower()
    m = re.search(r'\b(\d{1,2})\s*(?:лет|год|года|л\b)', t)
    if m:
        return int(m.group(1))
    m2 = re.search(r'\bмне\s*(\d{1,2})\b', t)
    if m2:
        return int(m2.group(1))
    m3 = re.search(r'\b(1[4-9]|[2-6]\d)\b', t)
    if m3:
        return int(m3.group(1))
    return 0

def extract_citizenship(text: str) -> str:
    if not text:
        return ""
    t = text.lower()
    if any(k in t for k in ["рф", "росси", "русск", "паспорт рф", "российск", "наш"]):
        return "РФ"
    for foreign in ["узбек", "таджик", "кырг", "киргиз", "армен", "беларус", "рб", "казах", "молдав", "снг"]:
        if foreign in t:
            return foreign.capitalize()
    return ""

def extract_gender(text: str) -> str:
    if not text:
        return ""
    t = text.lower()
    if any(k in t for k in ["парой", "паре", "с мужем", "с парнем", "с женой", "вдвоем", "семейн", "для пар", "парам"]):
        return "Пара"
    if any(k in t for k in ["женщин", "девушк", "женск", "я одна", "сама"]):
        return "Жен"
    if any(k in t for k in ["мужчин", "парен", "мужск", "я один", "сам"]):
        return "Муж"
    return ""

