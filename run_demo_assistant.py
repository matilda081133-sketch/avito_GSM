def extract_city(text: str) -> str:
    if not text:
        return ""
    t = text.lower()
    for c in KNOWN_CITIES:
        if c in t:
            return c.capitalize()
    m = re.search(r'\b(?:из|с|город|г\.)\s+([а-яё\-]{3,20})\b', t)
    if m:
        word = m.group(1).lower()
        if word not in ["выезжать", "уезжать", "москвы", "области", "россии", "дома", "себя", "работы", "этого"]:
            return word.capitalize()
    return ""

def extract_ready_date_info(text: str) -> tuple[str, str]:
    """Возвращает (date_text, date_iso_YYYY-MM-DD)."""
    if not text:
        return "", ""
    t = text.lower()
    now = datetime.datetime.now()
    year = now.year

    months = {
        'январ': 1, 'феврал': 2, 'март': 3, 'апрел': 4, 'ма': 5, 'июн': 6,
        'июл': 7, 'август': 8, 'сентябр': 9, 'октябр': 10, 'ноябр': 11, 'декабр': 12
    }

    # 1. '9 числа' / '12-го числа'
    m_num = re.search(r'\b(?:вые(?:хать|зд|ду)|заезд|готов|числа|с|на)?\s*(\d{1,2})\s*(?:-?[г|о]+го)?\s*числа\b', t)
    if not m_num:
        m_num = re.search(r'\b(\d{1,2})\s*(?:-?[г|о]+го)?\s*числа\b', t)
    if m_num:
        day = int(m_num.group(1))
        if 1 <= day <= 31:
            month = now.month
            if day < now.day:
                month = 1 if month == 12 else month + 1
                year = year + 1 if month == 1 else year
            return f"{day} числа", f"{year:04d}-{month:02d}-{day:02d}"

    # 2. '9 ноября' / '15 декабря'
    m_month = re.search(r'\b(\d{1,2})\s+([а-яё]+)\b', t)
    if m_month:
        day = int(m_month.group(1))
        m_word = m_month.group(2)
        for k, m_num_val in months.items():
            if m_word.startswith(k) and 1 <= day <= 31:
                return f"{day} {m_word}", f"{year:04d}-{m_num_val:02d}-{day:02d}"

    # 3. '09.11' or '09.11.2026'
    m_dot = re.search(r'\b(\d{1,2})\.(\d{1,2})(?:\.(\d{2,4}))?\b', t)
    if m_dot:
        d, m = int(m_dot.group(1)), int(m_dot.group(2))
        y = int(m_dot.group(3)) if m_dot.group(3) else year
        if y < 100:
            y += 2000
        return m_dot.group(0), f"{y:04d}-{m:02d}-{d:02d}"

    # 4. 'завтра', 'послезавтра', 'сегодня'
    if 'послезавтра' in t:
        target = now + datetime.timedelta(days=2)
        return 'послезавтра', target.strftime('%Y-%m-%d')
    if 'завтра' in t:
        target = now + datetime.timedelta(days=1)
        return 'завтра', target.strftime('%Y-%m-%d')
    if 'сегодня' in t or 'хоть сейчас' in t:
        return 'сегодня', now.strftime('%Y-%m-%d')

    return "", ""

def extract_ready_date(text: str) -> str:
    txt, _ = extract_ready_date_info(text)
    return txt

def strip_name_greetings(text: str, has_previous_dialogue: bool = False) -> str:
    """Удаляет любые обращения по имени в начале сообщения, а в продолжающемся диалоге срезает повторные приветствия и фразы-паразиты."""
    if not text:
        return text
    text = re.sub(r'^[А-ЯЁA-Za-z][а-яёA-Za-z0-9_-]+,\s*(здравствуйте|добрый день|добрый вечер|приветствую)', r'\1', text, flags=re.IGNORECASE)
    text = re.sub(r'^(здравствуйте|добрый день|добрый вечер|приветствую)[,\s]+[А-ЯЁA-Za-z][а-яёA-Za-z0-9_-]+[!\.,\s]*', r'\1! ', text, flags=re.IGNORECASE)
    text = re.sub(r'^[А-ЯЁA-Za-z][а-яёA-Za-z0-9_-]+,\s*', '', text)
    
    if has_previous_dialogue:
        text = re.sub(r'^(?:здравствуйте|добрый день|добрый вечер|приветствую)[!.,\s]*', '', text, flags=re.IGNORECASE).strip()
    
    # Срезаем фразу-паразит в конце
    text = re.sub(r'(?:[.,!]?\s*жду вашего ответа!?\s*)+$', '', text, flags=re.IGNORECASE).strip()
    
    text = text.strip()
    if text:
        text = text[0].upper() + text[1:]
    return text


def check_vahta_refusal(cand_text: str, combined_cand: str, ad_title: str, fac_key: str) -> tuple:
    """
    Проверяет, отказывается ли соискатель от вахты или требует только местную работу
    в своем региональном городе (например, в Армавире, Краснодаре, Уфе и др.).
    """
    t_curr = cand_text.lower().strip()
    t_comb = combined_cand.lower().strip()

    # 1. Если вакансия чисто местная (например, Смарт в Балашихе для местных или Стандарт в СПб)
    is_purely_local = (
        fac_key == "SMART_LOCAL" or
        ("стандарт" in ad_title.lower() and "спб" in ad_title.lower() and "вахт" not in ad_title.lower())
    )

    # Регулярные выражения явного отказа от вахты / поиска только местной работы
    refusal_patterns = [
        r'только\s+(?:в\s+[а-яё\-]+|у\s+себя|по\s+месту|по\s+городу|местн\w+)',
        r'(?:без|не\s+готов\w*|не\s+хоч\w*)\s+(?:выезд\w*|переезд\w*)',
        r'(?:на\s+)?вахт\w*\s+(?:не\s+(?:поед\w*|хоч\w*|интерес\w*|рассматр\w*|подход\w*)|мимо|отпадает)',
        r'не\s+(?:поед\w*|хоч\w*|рассматр\w*|интересует)\s+(?:на\s+)?вахт\w*',
        r'(?:ищу|нужн\w+|рассматрива\w*)\s+(?:только\s+)?(?:местн\w+|у\s+себя|в\s+своем\s+город\w+)',
        r'только\s+местн\w+',
        r'местн\w+\s+(?:ваканси\w+|работ\w+)',
        r'работ\w*\s+в\s+[а-яё\-]+(?:\s+уже)?\s+готов\w*\s+работать'
    ]
    import re
    combined_pat = re.compile(r'(?:' + '|'.join(refusal_patterns) + r')', re.IGNORECASE)

    m_curr = combined_pat.search(t_curr)
    m_comb = combined_pat.search(t_comb)

    if m_curr or m_comb:
        matched_text = (m_curr.group(0) if m_curr else m_comb.group(0)).lower()
        # Исключения для местных вакансий
        if "балаших" in matched_text and ("смарт" in fac_key.lower() or "балаших" in ad_title.lower()):
            return False, ""
        if ("питер" in matched_text or "спб" in matched_text) and ("стандарт" in fac_key.lower() or "спб" in ad_title.lower()):
            return False, ""

        # Если вакансия вахтовая, а соискатель требует работу только по месту / отказывается от вахты
        return True, f"Отказ от вахты / только местные вакансии ({matched_text})"

    return False, ""

