def detect_facility(text: str, vacancy_code: str = "", description: str = "") -> str:
    """
    Эталонная многоуровневая система распознавания проекта компании (GSM Logistics):
    - Приоритет №0: Системные префиксы в Id / VacancyCode (91.1% базы без текста)
    - Приоритет №0.5: Прямая строка <p>Код вакансии: [Объект]</p> в теле описания
    - Приоритет №1: Точные локации работы в тексте (без поля Address Авито!)
    - Приоритет №2: Уникальные продуктовые и брендовые маркеры
    """
    code_up = (vacancy_code or "").upper().strip()
    
    # 0.0 ПРОВЕРКА ПО БАЗЕ ЧИСЛОВЫХ ID (179 активных объявлений)
    if vacancy_code and vacancy_code in KNOWN_NUMERIC_ITEMS:
        return KNOWN_NUMERIC_ITEMS[vacancy_code]
    for num_id, fac in KNOWN_NUMERIC_ITEMS.items():
        if num_id in code_up:
            return fac

    desc_low = (description or "").lower()
    t = f"{code_up.lower()} {text or ''} {desc_low}".lower()

    # =========================================================================
    # ПРИОРИТЕТ №0: ПРЯМЫЕ ПРЕФИКСЫ В Id / VacancyCode
    # =========================================================================
    # 0.1 АБИ г. Владимир (ABI_..., ABI, HV_ABI_..., HV_OPR_..., HV_GRZ_...)
    if code_up.startswith(('ABI_', 'ABI', 'HV_ABI_', 'HV_OPR_', 'HV_GRZ_')):
        return 'ABI'

    # 0.2 Тепофол Кашира (TEP_, TEPOFOL_, TEPO_, HV_TEP_)
    if code_up.startswith(('TEP_', 'TEPOFOL_', 'TEPO_', 'HV_TEP_')):
        return 'TEPOFOL'

    # 0.3 Альфатехформ (ALF_, ALFA_, KLM_, KLIMOVSK_, V9_ALFA_, HV_ALF_, HV_SRT_)
    if code_up.startswith(('ALF_', 'ALFA_', 'KLM_', 'KLIMOVSK_', 'V9_ALFA_', 'HV_ALF_', 'HV_SRT_')) or "ALFATECH" in code_up:
        return 'ALFATECH'

    # 0.4 Смарт Family Балашиха (SMT_, SMART_, HV_SMT_)
    if code_up.startswith(('SMT_', 'SMART_', 'HV_SMT_')):
        if any(k in t for k in ["вахт", "проживан", "общежит", "квартир"]):
            return 'SMART_VAHTA'
        return 'SMART_LOCAL'

    # 0.5 Раменское (RAM_, ARNIKA_)
    if code_up.startswith(('RAM_', 'ARNIKA_')) or 'RAMENSK' in code_up:
        return 'ARNIKA_RAMENSKOE'

    # 0.6 Стандарт СПБ (V4_SPB_, STD_, HV_SPB_, SPB_)
    if code_up.startswith(('V4_SPB_', 'STD_', 'HV_SPB_', 'SPB_', 'STANDART')):
        return 'STANDART_SPB'
    # =========================================================================
    # ПРИОРИТЕТ №0.5: ПРЯМАЯ СТРОКА «КОД ВАКАНСИИ: [ОБЪЕКТ]» В ОПИСАНИИ
    # =========================================================================
    if "код вакансии" in t:
        if any(k in t for k in ["код вакансии: аби", "код вакансии:аби", "аби владимир"]):
            return 'ABI'
        if any(k in t for k in ["код вакансии: тепофол", "код вакансии:тепофол"]):
            return 'TEPOFOL'
        if any(k in t for k in ["код вакансии: альфатехформ", "код вакансии:альфатехформ", "код вакансии: альфа"]):
            return 'ALFATECH'
        if any(k in t for k in ["код вакансии: смарт", "код вакансии:смарт", "смарт family"]):
            if any(k in t for k in ["вахт", "проживан", "общежит", "квартир"]):
                return 'SMART_VAHTA'
            return 'SMART_LOCAL'
        if any(k in t for k in ["код вакансии: стандарт", "код вакансии:стандарт", "стандарт спб"]):
            return 'STANDART_SPB'

    # =========================================================================
    # ПРИОРИТЕТ №1 & №2: ЭТАЛОННАЯ МАТРИЦА МАРКЕРОВ (TITLE + DESCRIPTION)
    # =========================================================================

    # 1. Стандарт СПБ (Санкт-Петербург, оконные профили, ежедневные выплаты)
    if any(k in t for k in ["оконных профилей", "стеклопакет", "оконный профиль", "склад окон", "большевиков", "тепловозная", "обухово", "обуховской обороны", "металлопластик"]) or (any(c in t for c in ["санкт-петербург", "спб", "питер"]) and any(w in t for w in ["окон", "подработк", "3900", "3 900", "ежедневн", "стандарт"])):
        return 'STANDART_SPB'

    # 2. Тепофол (Кашира, рулонная теплоизоляция)
    # Завод / локация работы: в кашире, г. кашира, кашир..., кашира-1, ступино
    # Продукция: тепофол, утеплит..., теплоизоляц..., изоляци..., вспененн..., полиэтилен, упаковка рулонов, стрейч-пленка
    has_tepofol_prod = any(k in t for k in ["тепофол", "утеплит", "теплоизоляц", "вспененн", "фольгированн", "упаковка рулонов", "вспененный полиэтилен"])
    has_tepofol_loc = any(k in t for k in ["в кашире", "г. кашира", "кашир", "кашира-1", "ступино"])
    if has_tepofol_prod or (has_tepofol_loc and any(w in t for w in ["рулон", "изоляци", "полиэтилен", "строительные материалы", "упаковк"])):
        return 'TEPOFOL'

    # 3. Альфатехформ (Климовск / Подольск — пластиковые флаконы)
    # Продукция: альфатех..., флакон..., колбочк..., изделий из пластика, пластиков..., пэт, пресс-форм..., выдув, пузырьк..., пластмасс...
    # Локация работы: климовск..., подольск..., гривно, 50 лет октября, весенняя
    has_alfa_prod = any(k in t for k in ["альфатех", "альфатехформ", "флакон", "колбочк", "изделий из пластика", "выдув", "пузырьк", "световой стол", "отбраковк", "пресс-форм"])
    has_alfa_loc = any(k in t for k in ["климовск", "гривно", "50 лет октября", "весенняя"])
    if has_alfa_prod or has_alfa_loc or ("подольск" in t and any(w in t for w in ["пластик", "колпачк", "пэт", "пластмасс", "флакон", "колбочк"])):
        return 'ALFATECH'

    # 4. Смарт Family (Балашиха / Кучино — склад зоотоваров)
    # Продукция: смарт, smart family, petshop, зоотовары, корма для животных, товары для животных, товары для питомцев, сканер тсд
    # Локация работы: балаших..., кучин..., салтыковк..., новокосино, носовихинское
    has_smart_prod = any(k in t for k in ["smart family", "petshop", "зоотовары", "корма для животных", "товары для животных", "товары для питомцев", "сканер тсд", "ветпрепарат", "лотки", "наполнители"])
    has_smart_loc = any(k in t for k in ["балаших", "кучин", "салтыковк", "новокосино", "носовихинское"])
    if has_smart_prod or (has_smart_loc and any(w in t for w in ["зоо", "корма", "кошач", "собач", "смарт"])):
        if any(k in t for k in ["вахт", "проживан", "общежит", "квартир"]):
            return 'SMART_VAHTA'
        return 'SMART_LOCAL'

    # 5. Раменское (мебельный склад Арника)
    if any(k in t for k in ["раменск", "арник", "мебельн"]):
        return 'ARNIKA_RAMENSKOE'

    # 6. Автозапчасти (Подольск, склад запчастей)
    if any(k in t for k in ["автозапчаст", "запчаст", "китайск"]) or ("подольск" in t and not has_alfa_loc and not has_alfa_prod):
        return 'ALFA'

    # 7. АБИ г. Владимир (мясное производство)
    # ИСКЛЮЧЕНЫ общие фразы «3-разовое» и «пищевое» во избежание коллизий с Тепофолом и Смартом!
    # Уникальные бренды и продукция: аби, мясокомбинат, колбас..., сосиск..., сосисочн..., вязанк..., стародвор..., мясн...
    # Локация работы: во владимир, владимирск..., в г. владимир, г. владимир
    has_abi_prod = any(k in t for k in ["аби", "мясокомбинат", "колбас", "колбасн", "сосиск", "сосисочн", "вязанк", "стародвор", "горячая штучка", "мясн"])
    has_abi_loc = any(k in t for k in ["во владимир", "в г. владимир", "г. владимир", "владимирск"])
    if has_abi_prod or has_abi_loc:
        return 'ABI'

    # =========================================================================
    # БЕЗОПАСНЫЕ ФОЛЛБЕКИ (ТОЛЬКО ЕСЛИ ЯВНЫХ МАРКЕРОВ НЕТ)
    # =========================================================================
    # Если Санкт-Петербург / Питер в тексте — Стандарт СПБ
    if any(c in t for c in ["санкт-петербург", "питер", "спб"]):
        return 'STANDART_SPB'

    # Если "вахта", но нет признаков других регионов — по умолчанию АБИ Владимир
    if "вахт" in t:
        return 'ABI'

    # По умолчанию для местных складов в МО — Смарт Балашиха
    return 'SMART_LOCAL'

