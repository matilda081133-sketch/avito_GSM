def is_non_russian_name(name: str = "", text: str = "") -> bool:
    """Определяет нерусские, восточные, кавказские или среднеазиатские имена, требующие настороженности и проверки паспорта РФ."""
    combined = ((name or "") + " " + (text or "")).lower()
    words = re.findall(r'[а-яёa-z]+', combined)
    for w in words:
        if w in NON_RUSSIAN_NAME_ROOTS:
            return True
        if len(w) >= 5 and w.endswith(NON_RUSSIAN_SUFFIXES):
            return True
        if any(root in w for root in ["мухамм", "магомед", "абдул", "рахмон", "байрам", "курбан"]):
            return True
    return False

def has_explicit_rf_confirmation(text: str) -> bool:
    """Проверяет, есть ли прямое текстовое подтверждение гражданства РФ от кандидата."""
    if not text:
        return False
    t = text.lower()
    patterns = [
        r'\b(?:да,?\s*)?(?:паспорт\s+)?рф\b',
        r'\bграждан(?:ин|ка|ство)?\s+рф\b',
        r'\bпаспорт\s+(?:гражданина\s+)?рф\b',
        r'\bграждан(?:ин|ка|ство)?\s+росси[ия]\b',
        r'\bпаспорт\s+росси[ия]\b',
        r'\b(?:да,?\s*)?росси[яи]\b',
        r'\b(?:русский|русская|россиянин|россиянка)\b'
    ]
    for p in patterns:
        if re.search(p, t):
            return True
    return False

def check_is_fully_qualified(profile: dict, combined_cand: str, fac_key: str = "ABI") -> bool:
    """
    Проверяет, что кандидат подходит под выдачу ПРЯМОЙ ссылки в чат-бот МАКС:
    - Пол: строго мужчины для АБИ Владимир и Альфа (Тепофол — М/Ж)
    - Возраст: СТРОГО от 20 ДО 45 ЛЕТ (по возрасту прямая ссылка только до 45 лет, от 46 до 55 — только через рекрутера!)
    - Гражданство: строго паспорт РФ
    - Самозанятость и условия: согласен, нет отказов
    """
    if not profile:
        profile = {}

    # 1. Возраст для прямой ссылки в МАКС: строго от 20 до 45 лет!
    age = profile.get("age") or extract_age(combined_cand)
    if not age or age < 20 or age > 45:
        return False

    # 2. Гражданство: строго паспорт РФ
    # Нерусские имена ДОЛЖНЫ НАСТОРАЖИВАТЬ — нужно ВСЕГДА иметь прямое подтверждение паспорта РФ!
    cand_name = profile.get("candidate_name", "")
    is_non_rus = is_non_russian_name(cand_name, combined_cand)
    if is_non_rus:
        if not has_explicit_rf_confirmation(combined_cand):
            return False
    else:
        has_rf = profile.get("has_rf_passport")
        if has_rf is False:
            return False
        if has_rf is None:
            cit = extract_citizenship(combined_cand)
            if cit != "РФ":
                return False

    # 3. Пол: АБИ Владимир и Альфа — сейчас СТРОГО мужчины! Тепофол — М/Ж
    target_subj = profile.get("target_subject", "кандидат")
    is_third_male = target_subj in ["брат", "муж", "сын", "друг"]

    if fac_key in ["ABI"]:
        if not is_third_male:
            gender = profile.get("gender") or extract_gender(combined_cand, profile.get("candidate_name", ""))
            if gender == "Жен" or any(w in combined_cand.lower() for w in ["женщин", "девушк", "женск"]):
                return False

    # 4. Самозанятость: нет явного отказа
    t_comb = combined_cand.lower()
    if any(k in t_comb for k in ["не хочу самозан", "только по тк", "по тк только", "не буду самозан", "не подходит самозан"]):
        return False

    # 5. Условия устраивают
    if any(k in t_comb for k in ["не поеду", "мало платите", "не устраивает", "не подходит ставка"]):
        return False

    return True

def extract_phone_number(text: str) -> str:
    if not text:
        return ""
    raw = re.sub(r'[^\d+]', '', text)
    m = re.search(r'(?:\+?7|8)(9\d{9})', raw)
    if m:
        return f"+7{m.group(1)}"
    m2 = re.search(r'(?:\+?7|8)[\s\-\(]*(\d{3})[\s\-\)]*(\d{3})[\s\-]*(\d{2})[\s\-]*(\d{2})', text)
    if m2:
        return f"+7{m2.group(1)}{m2.group(2)}{m2.group(3)}{m2.group(4)}"
    return ""

def extract_avito_card_details(msgs: list) -> dict:
    """Извлекает из системных сообщений и плашек Авито параметры анкеты (возраст, гражданство, ФИО, телефон)."""
    res = {}
    for m in msgs:
        txt = m.get('content', {}).get('text', '') if isinstance(m, dict) else str(m)
        if not txt:
            continue
        # Возраст
        m_age = re.search(r'Возраст\s*[\n\r—–\-]*\s*(\d{1,2})\s*(?:лет|год|года)?', txt, flags=re.IGNORECASE)
        if m_age:
            val = int(m_age.group(1))
            if 14 <= val <= 85:
                res['age'] = val
        # Гражданство
        m_cit = re.search(r'Гражданство\s*[\n\r—–\-]*\s*([^\n\r]+)', txt, flags=re.IGNORECASE)
        if m_cit:
            cit_val = m_cit.group(1).strip()
            res['citizenship'] = cit_val
            if any(w in cit_val.lower() for w in ['росси', 'рф', 'русск']):
                res['has_rf_passport'] = True
            else:
                res['has_rf_passport'] = False
        # ФИО
        m_fio = re.search(r'ФИО\s*[\n\r—–\-]*\s*([^\n\r]+)', txt, flags=re.IGNORECASE)
        if m_fio:
            res['fio'] = m_fio.group(1).strip()
    return res

def extract_age(text: str) -> int:
    if not text:
        return 0
    t = text.lower().replace('\u00a0', ' ')
    # Первым делом проверяем формат карточки Авито: Возраст — 60 лет
    m_av = re.search(r'возраст\s*[\n\r—–\-]*\s*(\d{1,2})\s*(?:лет|год|года)?', t, flags=re.IGNORECASE)
    if m_av:
        val = int(m_av.group(1))
        if 14 <= val <= 85:
            return val

    # Игнорируем резюме и системные сообщения
    if '[системное сообщение]' in t or 'резюме' in t:
        # В тексте резюме возраст извлекаем только если прямо написано 'X лет/года'
        m_res = re.search(r'\b(\d{1,2})\s*(?:лет|год|года)\b', t)
        if m_res:
            val = int(m_res.group(1))
            if 16 <= val <= 75:
                return val
        return 0

    # Очищаем текст от зарплат, денег, смен, дней, часов и минут перед анализом
    cleaned = re.sub(r'\b\d+[\s]*(?:000|тыс|руб|р\b|₽)', ' ', t)
    cleaned = re.sub(r'\b\d+[\s]*(?:смен[а-я]*|дне[йя]|день|часов|часа|час|мин[а-я]*)', ' ', cleaned)
    cleaned = re.sub(r'\b\d{1,2}[.:]\d{1,2}\b', ' ', cleaned) # время

    # Исключаем вопросы об условиях/минимальном возрасте (вопросы для детей/родственников): "можно ли с 16 лет", "берут ли с 17 лет", "со скольки лет"
    cleaned = re.sub(r'\b(?:можно\s+ли|бер[её]те|принимаете|со\s+скольки|с\s+какого\s+возраста|работа(?:ть)?)\s*(?:у\s+вас\s*)?(?:с|от)?\s*\d{1,2}\s*(?:лет|года)?\b', ' ', cleaned, flags=re.IGNORECASE)
    cleaned = re.sub(r'\bс\s*\d{1,2}\s*(?:лет|года)?\s*(?:можно|бер[её]те|принимаете|работа(?:ть)?)\b', ' ', cleaned, flags=re.IGNORECASE)

    # 1. Приоритетный поиск: возраст с ключевыми словами (мне 25, брату 33, 47 лет, возраст 50)
    matches_kw = re.findall(r'\b(?:брату|мужу|сыну|мне|ему|ей|возраст)\s*(\d{1,2})\b', cleaned)
    if matches_kw:
        for m in reversed(matches_kw):
            val = int(m)
            if 14 <= val <= 75:
                return val

    matches_units = re.findall(r'\b(\d{1,2})\s*(?:лет|год|года|л\b)', cleaned)
    if matches_units:
        for m in reversed(matches_units):
            val = int(m)
            if 14 <= val <= 75:
                return val

    # 2. Если сообщение короткое (например '33', '25', '38 рф', '35 лет'), число на старте
    m_short = re.search(r'^\s*(\d{1,2})\b', cleaned.strip())
    if m_short:
        val = int(m_short.group(1))
        if 16 <= val <= 75:
            return val

    # 3. Число перед запятой или после точки
    m_sep = re.search(r'\b(\d{1,2})\s*[,.]', cleaned)
    if m_sep:
        val = int(m_sep.group(1))
        if 16 <= val <= 75:
            return val

    return 0

def extract_citizenship(text: str) -> str:
    if not text:
        return ""
    t = text.lower()
    if re.search(r'\b(?:рф|россия|россии|российск\w*|гражданин рф|гражданка рф|паспорт рф|русск\w*|наш)\b', t):
        return "РФ"
    # Короткие аббревиатуры СТРОГО как отдельные слова (чтобы не путать с чуРБанов, ущерб и т.д.):
    for acr in ["рб", "снг", "внж", "рвп", "пмр"]:
        if re.search(r'\b' + acr + r'\b', t):
            return acr.upper()
    foreign_roots = [
        "узбек", "таджик", "кырг", "киргиз", "армен", "армян", "беларус", "белорус",
        "казах", "молдав", "молдов", "тираспол", "приднестров", "кишинев", "украин",
        "патент", "иностран"
    ]
    for foreign in foreign_roots:
        if re.search(r'\b' + foreign, t):
            return foreign.capitalize()
    return ""

