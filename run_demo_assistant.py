def process_valeria_chat(chat_id: str, cand_name: str, item_title: str, msgs: list) -> bool:
    last_msg = msgs[-1]
    if last_msg.get('author_id') == AVITO_USER_ID:
        return False

    valeria_text = last_msg.get('content', {}).get('text', '').strip()
    if not valeria_text:
        return False

    print(f"\n[{datetime.datetime.now().strftime('%H:%M:%S')}] 🔥 СООБЩЕНИЕ ОТ ВАЛЕРИИ: '{valeria_text}'")

    # СБРОС СЕССИИ:
    # 1. Если кандидат пишет "заново", "сначала", "с чистого листа"
    # 2. Либо если предыдущий диалог был завершен ботом ("заявка на данный объект уже закрыта" / "удачи вам в поиске")
    is_explicit_restart = any(w in valeria_text.lower() for w in ["заново", "сначала", "с чистого листа", "начнем заново", "давай сначала", "рестарт"])

    last_close_idx = -1
    for idx, m in enumerate(msgs[:-1]):
        if m.get('author_id') == AVITO_USER_ID:
            t_bot = m.get('content', {}).get('text', '').lower()
            if any(phrase in t_bot for phrase in [
                "заявка на данный объект уже закрыта", 
                "удачи вам в поиске", 
                "удачи в поиске",
                "всего доброго"
            ]):
                last_close_idx = idx

    if is_explicit_restart:
        active_msgs = [last_msg]
        print("🔄 Обнаружена команда полного сброса диалога! Начинаем с чистого листа.")
    elif last_close_idx != -1:
        active_msgs = msgs[last_close_idx + 1:]
        print(f"🔄 Предыдущая сессия была закрыта. Начинаем новую сессию (активных сообщений: {len(active_msgs)}).")
    else:
        active_msgs = msgs

    # Историю кандидата и историю бота берем строго из АКТИВНОЙ сессии
    cand_msgs = [m.get('content', {}).get('text', '') for m in active_msgs if m.get('author_id') != AVITO_USER_ID and m.get('author_id') != 0]
    cand_history_only = " \n ".join(cand_msgs[:-1])

    our_msgs = [m.get('content', {}).get('text', '') for m in active_msgs if m.get('author_id') == AVITO_USER_ID]
    our_history = " \n ".join(our_msgs)

    reply_text, is_disqualified, disq_reason = generate_human_reply(
        cand_text=valeria_text,
        ad_title=item_title,
        cand_history_only=cand_history_only,
        our_history=our_history
    )

    if is_explicit_restart and not reply_text.startswith("Здравствуйте"):
        fac_key = detect_facility(item_title)
        intro_card = FACILITIES.get(fac_key, FACILITIES["ABI"])["intro"]
        reply_text = f"Валерия, договорились, начинаем с чистого листа!\n\n{intro_card}"

    print(f"🤖 ОТВЕТ АССИСТЕНТА:\n{reply_text}")

    res = client.send_message(chat_id, reply_text)
    print(f"✅ Отправлено в Авито! ID: {res.get('id', 'ok')}")
    client.mark_chat_as_read(chat_id)

    # Параметры извлекаем СТРОГО из текста активной сессии кандидата!
    all_cand_texts = " \n ".join(cand_msgs)
    fac_key = detect_facility(item_title + " " + all_cand_texts)
    fac_info = FACILITIES.get(fac_key, FACILITIES["ABI"])
    facility_name = fac_info["facility_name"]

    phone = extract_phone_number(all_cand_texts)
    age = extract_age(all_cand_texts)
    cit = extract_citizenship(all_cand_texts) or "РФ"
    city = extract_city(all_cand_texts)
    gender = extract_gender(all_cand_texts)

    cand_data = {
        "name": cand_name or "Валерия Цицилина",
        "phone": phone,
        "age": str(age) if age else "",
        "citizenship": cit,
        "city": city,
        "district": city,
        "gender": gender,
        "vacancy": item_title or fac_info["title"],
        "facility": facility_name
    }

    if is_disqualified:
        print(f"❌ НЕЦЕЛЕВОЙ: {disq_reason}. Обновляем CRM...")
        deal_res = sync_candidate_to_b24_deal(
            chat_id=chat_id,
            cand_data=cand_data,
            is_disqualified=True,
            disqualify_reason=f"Нецелевой: {disq_reason}"
        )
        print(f"✅ Сделка #{deal_res.deal_id} переведена в НЕУСПЕХ (код 204)!")
    else:
        deal_res = sync_candidate_to_b24_deal(
            chat_id=chat_id,
            cand_data=cand_data,
            is_disqualified=False
        )
        print(f"✅ CRM синхронизирована (Сделка #{deal_res.deal_id}, город: {city or 'не указан'})")

    return True

def check_and_reply_valeria():
    try:
        unread = client.get_unread_chats(limit=30)
        recent = client.get_recent_chats(limit=20)
        
        candidates = unread + recent
        seen = set()
        
        for c in candidates:
            cid = c.get('id')
            if not cid or cid in seen:
                continue
            seen.add(cid)
            
            users = c.get('users', [])
            cand_name = ""
            for u in users:
                if u.get('id') != AVITO_USER_ID:
                    cand_name = u.get('name', '')
                    break
            
            is_target = False
            if TARGET_CHAT_ID and cid == TARGET_CHAT_ID:
                is_target = True
            elif any(p in cand_name.lower() for p in ALLOWED_CANDIDATE_NAMES):
                is_target = True
                
            if not is_target:
                continue
                
            item_title = c.get('context', {}).get('value', {}).get('title', '')
            raw_msgs = client.get_chat_messages(cid, limit=50)
            if not raw_msgs:
                continue
                
            msgs = list(reversed(raw_msgs))
            return process_valeria_chat(cid, cand_name, item_title, msgs)
            
    except Exception as e:
        print(f"Ошибка проверки: {e}")
    return False

