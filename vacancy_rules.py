def detect_citizenship_from_text(text: str) -> tuple:
    if not text:
        return None, None
    t = text.lower()
    for key, enum_id in CITIZENSHIP_ENUM_MAP.items():
        if re.search(r'\b' + re.escape(key), t):
            name_label = "РФ" if enum_id == "68" else ("РБ" if enum_id == "70" else "СНГ")
            return enum_id, name_label
    return None, None

def detect_city_from_text(text: str) -> tuple:
    if not text:
        return None, None
    t = text.lower()
    for alias, (c_name, c_id) in CITY_ALIASES.items():
        if alias in t:
            return c_name, c_id
    cities_file = os.path.join(os.path.dirname(__file__), "cities_map.json")
    if os.path.exists(cities_file):
        try:
            with open(cities_file, "r", encoding="utf-8") as f:
                cities = json.load(f)
            for city_name, city_id in cities.items():
                if len(city_name) < 4:
                    continue
                stem = city_name[:-1] if len(city_name) > 4 else city_name
                if re.search(r'\b' + re.escape(stem), t):
                    return city_name.capitalize(), city_id
        except Exception:
            pass
    common = {
        "балаших": ("Балашиха", "1382"),
        "москв": ("Москва", "2018"),
        "владимир": ("Владимир", "1572"),
        "кашир": ("Кашира", "1950"),
        "реутов": ("Реутов", "2116"),
        "ногинск": ("Ногинск", "2068"),
        "красногорск": ("Красногорск", "1982"),
        "люберц": ("Люберцы", "2002"),
        "подольск": ("Подольск", "2096"),
        "раменск": ("Раменское", "2112")
    }
    for stem, (c_name, c_id) in common.items():
        if stem in t:
            return c_name, c_id
    return None, None

def evaluate_candidate_fit(vacancy_prof: dict, age_str: str, cit_str: str) -> dict:
    res = {
        "status": "NEEDS_VERIFICATION",
        "age_note": "",
        "cit_note": "",
        "rule_summary": f"Требования по вакансии: возраст {vacancy_prof.get('min_age', 18)}–{vacancy_prof.get('max_age', 55)} лет."
    }
    age_val = None
    if age_str:
        m = re.search(r'\d+', str(age_str))
        if m:
            age_val = int(m.group(0))
    if age_val is not None:
        min_a = vacancy_prof.get("min_age", 18)
        max_a = vacancy_prof.get("max_age", 55)
        if age_val < min_a:
            res["status"] = "UNDERAGE"
            res["age_note"] = f"К сожалению, по правилам объектов трудоустройство строго с {min_a} лет."
            return res
        elif age_val > max_a:
            res["status"] = "OVERAGE"
            res["age_note"] = f"По правилам данного объекта рассматриваются кандидаты до {max_a} лет."
        else:
            res["age_note"] = f"Возрастные рамки на объекте — от {min_a} до {max_a} лет."
    cit_lower = (cit_str or "").lower().strip()
    if cit_lower:
        is_direct = any(c in cit_lower for c in ["рф", "росси", "рб", "беларус"])
        if is_direct:
            res["cit_note"] = "Гражданство подходит под прямое оформление."
    return res
