def extract_phone(text: str) -> str:
    if not text:
        return ""
    raw_digits = re.sub(r'[^0-9+]', '', text)
    m = re.search(r'(?:\+?7|8)(9\d{9})', raw_digits)
    if m:
        return f"+7{m.group(1)}"
    phone_pattern = r'(?:\+?7|8)[\s\-\(]*(\d{3})[\s\-\)]*(\d{3})[\s\-]*(\d{2})[\s\-]*(\d{2})'
    m2 = re.search(phone_pattern, text)
    if m2:
        return f"+7{m2.group(1)}{m2.group(2)}{m2.group(3)}{m2.group(4)}"
    return ""

class CandidateSession:
    def __init__(self, chat_id: str, ad_title: str = "", candidate_name: str = ""):
        self.chat_id = chat_id
        self.ad_title = ad_title
        self.candidate_name = candidate_name
        self.phone = ""
        self.history = []
        self.state = "NEW"
        self.detected_vacancy = self.detect_vacancy(ad_title)

    def detect_vacancy(self, ad_title: str) -> str:
        t = (ad_title or "").lower()
        if any(w in t for w in ["аби", "владимир", "мясо", "колбас", "вязанк"]):
            return "АБИ Владимир (Вахта)"
        elif any(w in t for w in ["тепофол", "кашир", "утеплит"]):
            return "Тепофол Кашира (Вахта)"
        elif any(w in t for w in ["арник", "серпухов", "теплич", "овощ"]):
            return "Арника Серпухов (Вахта / Местные)"
        elif any(w in t for w in ["фарма", "опалих", "красногорск", "аптеч"]):
            return "Фарма Опалиха (Местные)"
        elif any(w in t for w in ["смарт", "балаших"]):
            return "Смарт Балашиха (Местные)"
        elif any(w in t for w in ["сдс", "брехов", "брёхов", "зоо"]):
            return "СДС Химки (Местные)"
        elif any(w in t for w in ["бьюти", "дмитровск", "косметик"]):
            return "Бьюти Москва (Местные)"
        elif any(w in t for w in ["шушар", "обухов", "санкт", "спб"]):
            return "СПб Шушары (Местные)"
        elif "вахт" in t:
            return "Общая Вахта"
        return "Местные смены"

    def is_vahta(self) -> bool:
        return "вахта" in self.detected_vacancy.lower() or "вахт" in (self.ad_title or "").lower()

class AIRecruiterEngine:
    def __init__(self):
        self.sessions = {}

    def get_or_create_session(self, chat_id: str, ad_title: str = "", candidate_name: str = "") -> CandidateSession:
        if chat_id not in self.sessions:
            self.sessions[chat_id] = CandidateSession(chat_id, ad_title, candidate_name)
        return self.sessions[chat_id]

    def process_message(self, chat_id: str, user_text: str, ad_title: str = "", candidate_name: str = "") -> str:
        session = self.get_or_create_session(chat_id, ad_title, candidate_name)
        
        # 1. Извлечение телефона
        extracted_phone = extract_phone(user_text)
        if extracted_phone and not session.phone:
            session.phone = extracted_phone
            session.state = "PHONE_OBTAINED"
            reply = (
                "Спасибо, контакты зафиксировала! Координатор свяжется с вами для согласования всех деталей и даты выхода. "
                "Если появятся вопросы — пишите прямо сюда в чат, мы на связи!"
            )
            session.history.append({"role": "user", "content": user_text})
            session.history.append({"role": "assistant", "content": reply})
            return reply

        # 2. Первое входящее касание (отклик)
        if len(session.history) == 0:
            session.history.append({"role": "user", "content": user_text})
            
            # Проверка анкеты Авито
            m_fio = re.search(r'ФИО\s*[—\-:]\s*([^\n\r]+)', user_text, re.IGNORECASE)
            m_age = re.search(r'Возраст\s*[—\-:]\s*(\d+)', user_text, re.IGNORECASE)
            m_cit = re.search(r'Гражданство\s*[—\-:]\s*([^\n\r]+)', user_text, re.IGNORECASE)

            cand_name = ""
            if m_fio:
                parts = m_fio.group(1).strip().split()
                if len(parts) >= 2:
                    cand_name = parts[1].capitalize() if parts[0].endswith(('ов', 'ев', 'ин', 'ва', 'на', 'ая', 'ий')) else parts[0].capitalize()
                elif parts:
                    cand_name = parts[0].capitalize()
            elif candidate_name:
                cand_name = candidate_name.split()[0].capitalize()

            age_val = m_age.group(1).strip() if m_age else ""
            cit_val = m_cit.group(1).strip() if m_cit else ""

            greeting = f"Здравствуйте, {cand_name}!" if cand_name else "Здравствуйте!"
            
            if age_val or cit_val:
                profile_summary = []
                if age_val: profile_summary.append(f"{age_val} лет")
                if cit_val: profile_summary.append(f"гражданство {cit_val}")
                summary_str = ", ".join(profile_summary)
                
                if session.is_vahta():
                    reply = (
                        f"{greeting} Вакансия актуальна, как раз сейчас распределяем места на заезд.\n\n"
                        f"Вашу анкету вижу ({summary_str}) — всё верно, данные актуальны?\n\n"
                        "Подскажите ещё два момента:\n"
                        "1. Из какого вы города и с какого числа готовы к выезду?\n"
                        "2. Ваш номер телефона для связи — я наберу, расскажу подробнее по заселению, питанию и забронирую место"
                    )
                else:
                    reply = (
                        f"{greeting} Вакансия актуальна, как раз сейчас формируем списки на ближайшие смены.\n\n"
                        f"Вашу анкету вижу ({summary_str}) — всё верно, данные актуальны?\n\n"
                        "Подскажите ещё два момента:\n"
                        "1. В каком районе вы проживаете и когда готовы выйти на смену (можно уже завтра)?\n"
                        "2. Ваш номер телефона для связи — я быстро наберу, сориентирую по остановке нашего автобуса и запишу на смену"
                    )
            else:
                if session.is_vahta():
                    reply = (
                        f"{greeting} Вакансия актуальна, сейчас формируем списки на заезд.\n\n"
                        "Подскажите, пожалуйста:\n"
                        "1. Из какого вы города и с какого числа готовы к выезду?\n"
                        "2. Ваш возраст и гражданство?\n\n"
                        "И напишите ваш номер телефона для связи — я наберу вас, подробно расскажу про условия и забронирую за вами место"
                    )
                else:
                    reply = (
                        f"{greeting} Вакансия актуальна, как раз ведем набор на смены.\n\n"
                        "Подскажите:\n"
                        "1. В каком районе вы проживаете и когда готовы выйти на смену (можно уже завтра)?\n"
                        "2. Ваш возраст и график (постоянный или подработка)?\n\n"
                        "И напишите номер телефона для связи — я быстро наберу, сориентирую по остановке нашего автобуса и запишу на смену"
                    )
            session.history.append({"role": "assistant", "content": reply})
            session.state = "IN_DIALOG"
            return reply

        # 3. Последующие вопросы кандидата
        session.history.append({"role": "user", "content": user_text})
        reply = self.generate_intelligent_reply(session, user_text)
        session.history.append({"role": "assistant", "content": reply})
        return reply

