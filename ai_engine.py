def extract_phone(text: str) -> str:
    if not text:
        return ""
    raw_digits = re.sub(r'[^0-9+]', '', text)
    m = re.search(r'(?:\+?7|8)(9\d{9})', raw_digits)
    if m:
        return f"+7{m.group(1)}"
    phone_pattern = r'(?:\+?7|8)[\s\-\(]*(\d{3})[\s\-\)]*(\d{3})[\s\-]*(\d{2})[\s\-]*(\d{2})'
    m2 = re.search(phone_pattern, text)
    if m2:
        return f"+7{m2.group(1)}{m2.group(2)}{m2.group(3)}{m2.group(4)}"
    return ""

class CandidateSession:
    def __init__(self, chat_id: str, ad_title: str = "", candidate_name: str = ""):
        self.chat_id = chat_id
        self.ad_title = ad_title
        self.candidate_name = candidate_name
        self.phone = ""
        self.history = []
        self.state = "NEW"
        self.detected_vacancy = self.detect_vacancy(ad_title)

    def detect_vacancy(self, ad_title: str) -> str:
        t = (ad_title or "").lower()
        if any(w in t for w in ["аби", "владимир", "мясо", "колбас", "вязанк", "стародвор"]):
            return "АБИ Владимир (Вахта)"
        elif any(w in t for w in ["тепофол", "кашир", "утеплит"]):
            return "Тепофол Кашира (Вахта)"
        elif any(w in t for w in ["альфа", "техформ", "подольск", "климовск", "колбочк", "флакон"]):
            return "Альфатехформ Подольск (Вахта)"
        elif any(w in t for w in ["смарт", "балаших", "зоо", "кучино"]):
            if "вахт" in t:
                return "Смарт Family вахта"
            return "Смарт Балашиха (Местные)"
        elif "вахт" in t:
            return "Общая Вахта"
        return "Местные смены"

    def is_vahta(self) -> bool:
        return "вахта" in self.detected_vacancy.lower() or "вахт" in (self.ad_title or "").lower()

